#!/usr/bin/env ruby
# The Markdown queue remains the publication authority; this is a local view.
require "cgi"
require "json"

module BlogQueue
  ROOT = File.expand_path("..", __dir__)
  SOURCE = File.join(ROOT, "blog/announcement-queue.md")
  OUTPUT = File.join(ROOT, "blog/announcement-queue.html")

  def self.entries(source)
    blocks = source.scan(/^## ([^\r\n]+)(?:\r?\n|\z)(.*?)(?=^## |\z)/m)
    raise "The file has no queue entries" if blocks.empty?
    raise "Malformed queue heading" unless blocks.length == source.lines.grep(/^##(?:[ \t]|$)/).length
    seen = {}
    blocks.map do |heading, body|
      raise "Each entry needs a numbered title: #{heading}" unless heading.match?(/\A[1-9]\d*\. \S[^\r\n]*\z/)
      matches = body.scan(/^- \[([ x])\] Ready to publish\r?$/)
      raise "Each entry needs exactly one exact readiness checkbox: #{heading}" unless matches.length == 1 && body.lines.grep(/^- \[/).length == 1
      quotes = body.lines.grep(/^>/).map(&:chomp).map { |line| line.delete_suffix("\r") }
      raise "Each entry needs one single-line quoted announcement: #{heading}" unless quotes.length == 1 && quotes.first.start_with?("> ")
      unknown = body.lines.map(&:chomp).map { |line| line.delete_suffix("\r") }.reject { |line| line.strip.empty? || line.start_with?("Topic: ", "> ") || line.match?(/\A- \[[ x]\] Ready to publish\z/) }
      raise "Unexpected content in queue entry: #{heading}" unless unknown.empty?
      message = quotes.first.delete_prefix("> ")
      match = message.match(%r{ (https://www\.gpeyre\.com/blog/preparations/([a-z0-9-]+)\.html)\z})
      raise "Announcement must end with its exact preview URL: #{heading}" unless match && !message.start_with?(" ")
      url, slug = match.captures
      raise "Duplicate queue slug: #{slug}" if seen[slug]
      seen[slug] = true
      { "title" => heading.sub(/^\d+\. /, ""), "topic" => (body[/^Topic: (.+)$/, 1] || "Other topics").strip,
        "ready" => matches.first.first == "x", "message" => message, "url" => url,
        "slug" => slug }
    end
  end

  def self.images
    path = File.join(ROOT, "blog/summary-images.json")
    return {} unless File.exist?(path)
    manifest = JSON.parse(File.read(path, encoding: "UTF-8"))
    raise "Unsupported summary-image manifest" unless manifest["version"] == 1 && manifest["images"].is_a?(Hash)
    manifest["images"].select do |_slug, image|
      image["path"].to_s.match?(%r{\A/blog/imgs/summaries/[a-z0-9-]+\.(jpg|jpeg|png|webp)\z})
    end
  end

  def self.escape(value)
    CGI.escapeHTML(value.to_s)
  end

  def self.card(entry, index, catalogue)
    image = catalogue[entry["slug"]]
    picture = if image
      path = image.fetch("path").delete_prefix("/blog/")
      %(<a class="queue-picture" href="#{escape(path)}" aria-label="Open illustration for #{escape(entry['title'])}"><img src="#{escape(path)}" alt="#{escape(image['alt'])}" width="#{image['width'].to_i}" height="#{image['height'].to_i}" loading="lazy"></a>)
    else
      %(<div class="queue-picture queue-no-picture"><span>#{escape(entry['topic'])}</span><p>#{escape(entry['title'])}</p><small>No numerical illustration</small></div>)
    end
    <<~HTML
      <article class="queue-card" data-slug="#{escape(entry['slug'])}">
        #{picture}
        <div class="queue-card-body"><div class="queue-card-meta"><span class="queue-order">#{format('%02d', index + 1)}</span><span>#{escape(entry['topic'])}</span></div>
        <h2><a href="#{escape(entry['url'])}">#{escape(entry['title'])}</a></h2>
        <p class="queue-announcement">#{escape(entry['message'])}</p>
        <div class="queue-card-actions"><label class="queue-ready"><input type="checkbox" disabled#{entry['ready'] ? ' checked' : ''}><span>Ready to publish</span></label><a href="#{escape(entry['url'])}">Read preview <span aria-hidden="true">↗</span></a></div></div>
      </article>
    HTML
  end

  def self.render
    source = File.read(SOURCE, encoding: "UTF-8")
    records = entries(source)
    catalogue = images
    data = JSON.generate({ "source" => source, "images" => catalogue }).gsub("<", "\\u003c").gsub("\u2028", "\\u2028").gsub("\u2029", "\\u2029")
    <<~HTML
      <!doctype html>
      <!-- Generated by scripts/build-blog-queue.rb. Local editorial view, not a public page. -->
      <html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="robots" content="noindex,nofollow"><title>Blog editorial queue · Gabriel Peyré</title><link rel="stylesheet" href="../css/blog-queue.css"><script src="../js/blog-queue.js" defer></script></head>
      <body><header class="queue-header"><div class="queue-shell"><div class="queue-masthead"><a href="https://www.gpeyre.com/blog/">Gabriel Peyré / Blog</a><span>Private editorial workspace</span></div><p class="queue-eyebrow">Forthcoming articles</p><h1>The publication queue.</h1><p class="queue-intro">Read, review, and prepare the next story. A readiness box approves both the article and its announcement. Save your edits to the original Markdown queue, then ask Codex to commit and push them before the next scheduled run.</p>
      <div class="queue-overview"><div><strong data-count-total>#{records.length}</strong><span>forthcoming</span></div><div><strong data-count-ready>#{records.count { |record| record['ready'] }}</strong><span>approved</span></div><div><strong data-count-images>#{records.count { |record| catalogue.key?(record['slug']) }}</strong><span>illustrated</span></div><a href="published.md">Published archive <span aria-hidden="true">↗</span></a></div></div></header>
      <main class="queue-shell"><section class="queue-edit-panel" aria-label="Save queue changes"><div><h2>Markdown is the source of truth.</h2><p>This generated snapshot can be stale. Use <strong>Open current Markdown</strong> before editing a file changed elsewhere. Boxes are drafts until saved to <code>blog/announcement-queue.md</code>; order and announcements are preserved. Unsaved or uncommitted queue changes can stop the scheduled workflow.</p><p class="queue-save-status" data-save-status role="status" aria-live="polite">Showing the queue embedded when this page was generated.</p></div><div class="queue-file-actions"><button type="button" data-open disabled>Open current Markdown</button><button type="button" data-save disabled>Save to source</button><button type="button" data-download disabled>Download Markdown</button></div><input type="file" accept=".md,text/markdown,text/plain" data-file-input hidden></section>
      <section class="queue-toolbar" aria-label="Filter articles"><label class="queue-search">Search the queue<input type="search" placeholder="Title, topic, or announcement…" data-search disabled></label><label>Readiness<select data-ready-filter aria-label="Readiness" disabled><option value="all">All posts</option><option value="ready">Ready to publish</option><option value="review">Under review</option></select></label><label>Topic<select data-topic-filter aria-label="Topic" disabled><option value="all">All topics</option><option value="ot">Optimal transport</option><option value="transport">Other transport geometry</option><option value="other">Other topics</option></select></label></section>
      <p class="queue-results" data-results role="status" aria-live="polite">#{records.length} articles · source order</p><noscript><p class="queue-notice">Enable JavaScript to filter or edit readiness. You can still read every preview below. Edit announcement-queue.md directly to change approvals.</p></noscript><div class="queue-grid" data-cards>#{records.each_with_index.map { |record, index| card(record, index, catalogue) }.join}</div><p class="queue-empty" data-empty hidden>No articles match these filters.</p>
      <aside class="queue-copy-fallback" data-copy-fallback hidden><label>Copy this announcement<textarea readonly data-copy-text rows="4"></textarea></label><button type="button" data-close-copy>Close</button></aside>
      <footer class="queue-footer"><p>Readiness edits do not publish an article or send a Bluesky post. The scheduled publication workflow reads the original Markdown queue and stops on overlapping uncommitted changes. After saving, ask Codex to review, commit, and push your queue edits before the next scheduled run.</p><p>Downloaded files have no effect until you replace <code>blog/announcement-queue.md</code> and synchronize those changes. This generated HTML is only a snapshot. Open the current file again after external edits; source conflicts are reported instead of silently merged.</p></footer></main>
      <script type="application/json" id="queue-data">#{data}</script></body></html>
    HTML
  end
end

if $PROGRAM_NAME == __FILE__
  expected = BlogQueue.render
  if ARGV == ["--check"]
    abort "Editorial HTML is stale. Run ruby scripts/build-blog-queue.rb." unless File.exist?(BlogQueue::OUTPUT) && File.read(BlogQueue::OUTPUT, encoding: "UTF-8") == expected
    puts "Editorial queue HTML is current."
  elsif ARGV.empty?
    File.write(BlogQueue::OUTPUT, expected)
    puts "Built local editorial queue HTML."
  else
    abort "Usage: ruby scripts/build-blog-queue.rb [--check]"
  end
end
