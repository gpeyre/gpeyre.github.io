#!/usr/bin/env ruby
# Build a static, dependency-free search catalogue from article metadata.
require "cgi"
require "date"
require "json"
require "time"
require "yaml"

module BlogSearchIndex
  ROOT = File.expand_path("..", __dir__)
  OUTPUT = File.join(ROOT, "js", "blog-search-index.js")

  def self.plain(text)
    CGI.unescapeHTML(text.to_s.gsub(/<[^>]*>/, " ")).gsub(/\s+/, " ").strip
  end

  def self.keywords(values, source)
    unless values.is_a?(Array) && values.all? { |value| value.is_a?(String) }
      raise "#{source}: keywords must be a list of strings"
    end
    words = values.map { |value| plain(value) }.reject(&:empty?)
    normalized = words.map { |word| word.unicode_normalize(:nfkd).gsub(/\p{Mn}/, "").downcase }
    raise "#{source}: duplicate keywords" unless normalized.uniq.size == normalized.size
    raise "#{source}: supply at least 18 specific keywords" if words.size < 18
    words
  end

  def self.meta(html, name)
    html.scan(/<meta\b[^>]*>/i).each do |tag|
      attrs = tag.scan(/([\w:-]+)\s*=\s*(["'])(.*?)\2/m).to_h { |key, _quote, value| [key.downcase, CGI.unescapeHTML(value)] }
      return attrs["content"] if attrs["name"].to_s.downcase == name
    end
    nil
  end

  def self.records
    published = Dir.glob(File.join(ROOT, "blog", "_posts", "*.md")).sort.filter_map do |path|
      source = path.delete_prefix(ROOT + "/")
      matter = File.read(path, encoding: "UTF-8").match(/\A---\s*\n(.*?)\n---\s*\n/m)
      raise "#{source}: missing front matter" unless matter
      data = YAML.safe_load(matter[1], permitted_classes: [Date, Time])
      next if data["published"] == false
      stamp, slug = File.basename(path).match(/\A(\d{4}-\d{2}-\d{2})-(.+)\.md\z/).captures
      date = Date.parse((data["date"] || stamp).to_s)
      url = data["permalink"] || "/blog/#{date.strftime('%Y/%m/%d')}/#{data['slug'] || slug}/"
      {
        "id" => source, "url" => url, "status" => "published", "date" => date.iso8601,
        "title" => plain(data.fetch("title")), "description" => plain(data.fetch("description")),
        "keywords" => keywords(data["keywords"], source)
      }
    end
    forthcoming = Dir.glob(File.join(ROOT, "blog", "preparations", "*.html")).sort.filter_map do |path|
      next if File.basename(path) == "index.html"
      source = path.delete_prefix(ROOT + "/")
      html = File.read(path, encoding: "UTF-8")
      matter = html.match(/\A---\s*\n(.*?)\n---\s*\n/m)
      next if matter && YAML.safe_load(matter[1], permitted_classes: [Date, Time])["redirect_to"]
      title = html.match(/<h1\b[^>]*>(.*?)<\/h1>/mi)&.captures&.first
      raise "#{source}: missing article heading" unless title
      {
        "id" => source, "url" => "/" + source, "status" => "forthcoming", "date" => nil,
        "title" => plain(title), "description" => plain(meta(html, "description")),
        "keywords" => keywords(meta(html, "keywords")&.split(","), source)
      }
    end
    all = published + forthcoming
    all.each do |post|
      raise "#{post['id']}: missing title or description" if post["title"].empty? || post["description"].empty?
      unless post["url"].start_with?("/blog/") && !post["url"].match?(/[?#<>\s]/)
        raise "#{post['id']}: unsupported article URL #{post['url'].inspect}"
      end
    end
    raise "Duplicate search URLs" unless all.map { |post| post["url"] }.uniq.size == all.size
    all.sort_by { |post| [post["status"] == "published" ? 0 : 1, post["url"]] }
  end

  def self.render
    json = JSON.pretty_generate(records).gsub("<", "\\u003c").gsub("\u2028", "\\u2028").gsub("\u2029", "\\u2029")
    "/* Generated by scripts/build-blog-search.rb; edit the keywords in each article. */\n" \
      "window.BLOG_SEARCH_RECORDS = #{json};\n"
  end
end

if $PROGRAM_NAME == __FILE__
  expected = BlogSearchIndex.render
  if ARGV == ["--check"]
    abort "Search catalogue is stale. Run ruby scripts/build-blog-search.rb." unless
      File.exist?(BlogSearchIndex::OUTPUT) && File.read(BlogSearchIndex::OUTPUT, encoding: "UTF-8") == expected
    puts "Blog search catalogue is current."
  elsif ARGV.empty?
    File.write(BlogSearchIndex::OUTPUT, expected)
    counts = BlogSearchIndex.records.group_by { |post| post["status"] }.transform_values(&:size)
    puts "Built search catalogue: #{counts.map { |key, count| "#{count} #{key}" }.join(', ')}."
  else
    abort "Usage: ruby scripts/build-blog-search.rb [--check]"
  end
end
